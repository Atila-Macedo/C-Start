// Variáveis
double projeto1 = 7;
double projeto2 = 5;

// Operador E  (O operador && retorna true se ambas as condições forem verdadeiras)
Console.WriteLine(projeto2 >= 7 && projeto1 >= 7);

// Operador OU (O operador || retorna true se pelo menos uma das condições for verdadeira)
Console.WriteLine(projeto1 >= 7 || projeto2 >= 7);

// Operado de negação
Console.WriteLine(!true);