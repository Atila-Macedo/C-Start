// Variáveis
int numero1 = 5;
int numero2 = 8;

// Maior que
Console.WriteLine(numero1 > numero2);

// Maior ou igual que
Console.WriteLine(numero1 >= numero2);

// Menor que
Console.WriteLine(numero1 < numero2);

// Menor ou igual que
Console.WriteLine(numero1 <= numero2);

// Igual a
Console.WriteLine(numero1 == numero2);

// Diferente de
Console.WriteLine(numero1 != numero2);